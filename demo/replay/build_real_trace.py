#!/usr/bin/env python3
"""Turn two recorded runs into real-trace.js for the replay page.

  python3 build_real_trace.py TASK.ec WITH.jsonl WITHOUT.jsonl [--line N] [--note-en ... --note-zh ...]

TASK.ec        the file both agents started from (e.g. proofs/elgamal.ec on main)
WITH.jsonl     one {t, dur, tool, args, result} per MCP tool call, as logged by the ec-tool wrapper
WITHOUT.jsonl  `_snapshot` (file text at each compile) + `bash` (easycrypt compile output) rows
--line N       where the missing proof goes (default: the first `qed.` right after a `proof.`)

Times are real wall-clock seconds from each lane's first logged call. In the without lane the
agent's edits are not logged themselves; each one is reconstructed from the file snapshot taken at
the next compile and shown 1 s before it.
"""
import argparse, json, os, re

ap = argparse.ArgumentParser()
ap.add_argument("task"); ap.add_argument("with_log"); ap.add_argument("without_log")
ap.add_argument("--line", type=int)
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "real-trace.js"))
ap.add_argument("--note-en", default=""); ap.add_argument("--note-zh", default="")
a = ap.parse_args()

start = open(a.task).read().rstrip("\n").split("\n")
line = a.line or next(i + 1 for i in range(1, len(start))
                      if start[i].strip() == "qed." and start[i - 1].strip() == "proof.")
lemma = next(m.group(1) for l in reversed(start[:line]) if (m := re.search(r"lemma\s+(\w+)", l)))
rows = lambda p: [json.loads(l) for l in open(p) if l.strip()]

def lane_with(evs):
    t0 = evs[0]["t"]
    out = [{"t": round(e["t"] - t0, 1), "tool": e["tool"], "args": e["args"], "result": e["result"]} for e in evs]
    if not any(e["tool"] == "check_file" and e["result"].get("ok") for e in out):
        last = evs[-1]; out.append({"t": round(last["t"] + last["dur"] - t0, 1), "tool": "stop", "args": {"reason": "budget"}, "result": {"ok": False}})
    return out

def lane_without(evs):
    t0 = evs[0]["t"] - 1
    prev, out = start, []
    for e in evs:
        if e["tool"] == "_snapshot":
            cur = e["result"]["text"].rstrip("\n").split("\n")
            i = 0
            while i < min(len(prev), len(cur)) and prev[i] == cur[i]: i += 1
            j = 0
            while j < min(len(prev), len(cur)) - i and prev[-1 - j] == cur[-1 - j]: j += 1
            if cur != prev:  # lines i+1 .. len(prev)-j of the old file became cur[i:len(cur)-j]
                out.append({"t": round(e["t"] - t0 - 1, 1), "tool": "edit",
                            "args": {"path": os.path.basename(e["args"]["path"]), "start": i + 1, "end": len(prev) - j,
                                     "text": "\n".join(cur[i:len(cur) - j])}, "result": {"ok": True}})
            prev = cur
        else:
            out.append({"t": round(e["t"] - t0, 1), "tool": e["tool"], "args": e["args"], "result": e["result"]})
    if not (out and out[-1]["tool"] == "bash" and out[-1]["result"].get("ok")):
        last = evs[-1]; out.append({"t": round(last["t"] + last["dur"] - t0, 1), "tool": "stop", "args": {"reason": "budget"}, "result": {"ok": False}})
    return out

w, wo = rows(a.with_log), rows(a.without_log)
final = next((e["result"]["text"] for e in reversed(wo) if e["tool"] == "_snapshot"), "\n".join(start)).rstrip("\n").split("\n")
data = {
    "mock": False,
    "source": {"en": a.note_en, "zh": a.note_zh},
    "file": {"name": os.path.basename(a.task), "start": start, "final": final, "hole": [line, line - 1],
             "task": f"Fill in the missing proof of lemma {lemma} (before line {line})",
             "task_zh": f"补全引理 {lemma} 缺失的证明（第 {line} 行之前）"},
    "lanes": {"with": {"title": "With MCP", "events": lane_with(w)},
              "without": {"title": "Without MCP", "events": lane_without(wo)}},
}
with open(a.out, "w") as f:
    f.write("// Generated by build_real_trace.py from recorded runs; do not edit by hand.\n")
    f.write("window.REPLAY_DATA_REAL = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print(f"wrote {a.out}: with {len(data['lanes']['with']['events'])} events, without {len(data['lanes']['without']['events'])} events")
