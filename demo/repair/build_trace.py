#!/usr/bin/env python3
"""Turn a recorded repair run (run/) into trace.js for index.html.

  python3 build_trace.py            # reads run/*, writes trace.js

run/task-elgamal.ec      demo/elgamal.ec with line 79 (`swap{1} 7 -5.`) deleted — the agent's starting file
run/trace.jsonl          one {t, dur, tool, args, result} per tool call, written by run/rec.py
run/repaired-elgamal.ec  the file after the run
run/final-check.txt      `easycrypt llm -lastgoals` on the repaired file, plus its exit code

Everything shown on the page comes from these files except NOTES below: the agent's one-line
reasoning for each call, written at the time of the run.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
RUN = os.path.join(HERE, "run")
DELETED_LINE, DELETED_TEXT = 79, "  swap{1} 7 -5."

# (en, zh) per recorded call, same order as trace.jsonl
NOTES = [
    ("Is the toolchain alive? Alt-Ergo and Z3 are detected.",
     "工具链可用吗？检测到 Alt-Ergo 和 Z3。"),
    ("Check the whole file. It fails at line 80: `auto; call (_:true).` — \"invalid last instruction\". "
     "The first `auto; call` (line 79) went through; the second one cannot reach a `call`.",
     "检查整个文件。第 80 行 `auto; call (_:true).` 失败：\"invalid last instruction\"。"
     "第 79 行的第一个 `auto; call` 通过了，第二个却走不到 `call`。"),
    ("Read the goal just before line 80. Two programs, one per game. Walking back from the end, "
     "left line 7 samples y <$ dt, right line 7 samples b0 <$ {0,1}: different distributions, so they cannot be coupled.",
     "读取第 80 行之前的目标。左右两个游戏程序。从后往前对齐：左边第 7 行采样 y <$ dt，"
     "右边第 7 行采样 b0 <$ {0,1}——分布不同，无法耦合。"),
    ("Confirm: plain `auto.` only eats the final assignment and stops exactly at the y-vs-b0 mismatch.",
     "验证：单独 `auto.` 只吃掉最后的赋值，正好停在 y 与 b0 不匹配处。"),
    ("Right samples y before A.choose (its line 2). Move the left y <$ dt from 7 up to 3, just before A.choose: "
     "`swap{1} 7 -4.` Now the tails line up: b <-> b0, A.choose <-> A.choose, y <-> y.",
     "右边在 A.choose 之前采样 y（第 2 行）。把左边第 7 行的 y <$ dt 移到第 3 行、A.choose 之前："
     "`swap{1} 7 -4.` 现在两边对齐：b ↔ b0，A.choose ↔ A.choose，y ↔ y。"),
    ("The snippet passed, so write exactly those bytes into the file. One accepted step = one git commit.",
     "片段通过检查，把完全相同的文本写入文件。每个通过的步骤 = 一次 git 提交。"),
    ("Re-check the whole file from line 1: no diagnostics, exit 0. The proof is complete.",
     "从第 1 行重新检查整个文件：无错误，退出码 0。证明完成。"),
]


def main():
    rows = [json.loads(l) for l in open(os.path.join(RUN, "trace.jsonl")) if l.strip()]
    assert len(rows) == len(NOTES), (len(rows), len(NOTES))
    t0 = rows[0]["t"]
    steps = []
    for r, (en, zh) in zip(rows, NOTES):
        res = dict(r["result"])
        # the OCaml-version warning is noise for this page; keep everything else
        if "garbage-collector regression" in res.get("raw_stderr", ""):
            res["raw_stderr"] = ""
        if r["tool"] == "easycrypt_config":
            # keep the version and solver lines; the load path is just local install paths
            res["output"] = "\n".join(l for l in res.get("output", "").splitlines()
                                      if re.match(r"\s*(git-hash|Known provers|timeout)", l))
        args = {k: (os.path.basename(v) if k == "path" else v) for k, v in r["args"].items()}
        steps.append({"t": round(r["t"] - t0, 1), "dur": r["dur"], "tool": r["tool"], "args": args,
                      "result": res, "note": {"en": en, "zh": zh}})
    final = open(os.path.join(RUN, "final-check.txt")).read()
    final_exit = int(re.search(r"exit=(\d+)", final).group(1))
    final_out = "\n".join(l for l in final.splitlines()
                          if not l.startswith("exit=") and "garbage-collector" not in l).strip()
    data = {
        "task": open(os.path.join(RUN, "task-elgamal.ec")).read(),
        "repaired": open(os.path.join(RUN, "repaired-elgamal.ec")).read(),
        "deleted": {"line": DELETED_LINE, "text": DELETED_TEXT},
        "steps": steps,
        "final": {"exit": final_exit, "out": final_out},
    }
    out = os.path.join(HERE, "trace.js")
    with open(out, "w") as f:
        f.write("// generated by build_trace.py from run/ — real EasyCrypt output, do not edit\n")
        f.write("window.REPAIR = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    print("wrote", out, len(steps), "steps")


if __name__ == "__main__":
    main()
